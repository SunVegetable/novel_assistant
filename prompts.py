# 提示词集中管理（短剧版）
# 短剧方法论的核心：爽点不是写正文时即兴发挥，而是在大纲阶段逐集排定。
# 本文件三个层次：
#   1) 基础设定 —— 立住"逆袭主角 + 欠打脸反派"的人设底盘
#   2) 总纲+分幕 —— 排全剧节奏（幕=爽点节奏单位）
#   3) 分集大纲 —— 每集一行：标题/剧情/爽点/钩子，90集全部提前排完
#   4) 单集剧本 —— 严格按分集大纲的爽点/钩子落地成台本
